"""Builds RESULTS.md (every variant tried + its scores) and latex/results_table.tex (the
report's tab:results) from the run logs:
  - outputs/retrieval_results.jsonl  (written by eval_retrieval.py)
  - outputs/dev_*.scores.json        (written by run_rag.py, judge score added by judge.py)
  - leaderboard_scores.json          (entered by hand, keyed by run name, e.g. {"dev_hybrid_rrf": 41.7})

    python make_results_table.py
"""
import datetime
import glob
import json
import os

from rag.pipeline import CORPUS, DEFAULT_RERANKER, corpus_version

# display order and names for QA runs; any other dev_* run is appended under its file stem
SYSTEMS = [
    ("dev_closed_book", "Closed-book"),
    ("dev_dense", "Dense only"),
    ("dev_sparse", "Sparse only"),
    ("dev_hybrid_rrf", "Hybrid RRF"),
    ("dev_hybrid_weighted", "Hybrid weighted"),
    ("dev_hybrid_rrf_rerank", "Hybrid RRF + rerank"),
    ("dev_v2_adaptive", "v2: adaptive answers"),
    ("dev_v2_adaptive_bge", "v2: adaptive + bge reranker"),
    ("dev_v2_adaptive_14b", "v2: adaptive + 14B reader"),
    ("dev_v2_full", "v2: adaptive + bge reranker + 14B reader"),
    ("dev_v3", "v3: 14B adaptive + answer fixes"),
]
RETRIEVAL_LOG = "outputs/retrieval_results.jsonl"
KS = ["1", "3", "5", "10"]


def load_qa_runs(version):
    """Returns (current, stale): runs on the current corpus vs. runs on an older scrape.
    Closed-book runs don't use the corpus, so they are never stale."""
    runs = {}
    for path in glob.glob("outputs/dev_*.scores.json"):
        with open(path) as f:
            runs[os.path.basename(path).removesuffix(".scores.json")] = json.load(f)
    names = dict(SYSTEMS)
    order = [s for s, _ in SYSTEMS if s in runs] + sorted(s for s in runs if s not in names)
    rows = [(s, names.get(s, s), runs[s]) for s in order]
    is_current = lambda r: r["config"].get("closed_book") or r.get("corpus") == version
    return [x for x in rows if is_current(x[2])], [x for x in rows if not is_current(x[2])]


def retrieval_key(r):
    return (r["chunking"], r["chunk_size"], r["retriever"], r["fusion"] or "", r["alpha"] or 0,
            r["embedder"] or "", r["rerank"], (r.get("reranker") or DEFAULT_RERANKER) if r["rerank"] else "")


def load_retrieval_runs(version):
    """Returns (current, stale) retrieval runs; re-running a config replaces its old row."""
    if not os.path.exists(RETRIEVAL_LOG):
        return [], []
    current, stale = {}, {}
    with open(RETRIEVAL_LOG) as f:
        for line in f:
            r = json.loads(line)
            (current if r.get("corpus") == version else stale)[retrieval_key(r)] = r
    stale = {k: r for k, r in stale.items() if k not in current}
    return sorted(current.values(), key=retrieval_key), sorted(stale.values(), key=retrieval_key)


def pct(scores, key):
    return f"{100 * scores[key]:.1f}" if key in scores else ""


def qa_row(stem, scores, leaderboard):
    lb = leaderboard.get(stem)
    judge = f"{scores['judge']:.2f}" if "judge" in scores else ""
    return [pct(scores, "recall"), pct(scores, "f1"), pct(scores, "rougeL"), judge, "--" if lb is None else str(lb)]


def setup(cfg):
    if cfg.get("closed_book"):
        return "no retrieval"
    parts = [f"{cfg['chunking']}-{cfg['chunk_size']}", cfg["retriever"]]
    if cfg["retriever"] == "hybrid":
        parts.append(f"{cfg['fusion']} α={cfg['alpha']}")
    if cfg["retriever"] != "sparse":
        parts.append(cfg["embedder"].split("/")[-1])
    if cfg.get("rerank"):
        reranker = cfg.get("reranker") or DEFAULT_RERANKER
        parts.append("+rerank" + (f" ({reranker.split('/')[-1]})" if reranker != DEFAULT_RERANKER else ""))
    parts.append(f"top-{cfg['top_k']}")
    if cfg.get("answer_style", "short") != "short":
        parts.append(f"{cfg['answer_style']} answers")
    if cfg.get("reader_model"):
        parts.append(f"reader {cfg['reader_model'].split('/')[-1]}")
    return ", ".join(parts)


def retrieval_label(r):
    if r["retriever"] == "sparse":
        label = "BM25"
    elif r["retriever"] == "dense":
        label = f"dense ({r['embedder'].split('/')[-1]})"
    else:
        label = f"hybrid {r['fusion']} α={r['alpha']}"
        if r["embedder"] and "bge-m3" not in r["embedder"]:
            label += f" ({r['embedder'].split('/')[-1]})"
    if not r["rerank"]:
        return label
    reranker = r.get("reranker") or DEFAULT_RERANKER
    return label + " + rerank" + (f" ({reranker.split('/')[-1]})" if reranker != DEFAULT_RERANKER else "")


def build_markdown(qa, retr, leaderboard, version, stale_qa, stale_retr):
    modified = datetime.datetime.fromtimestamp(os.path.getmtime(CORPUS))
    with open(CORPUS) as f:
        n_docs = len(json.load(f))
    md = ["# Results", "",
          f"*Auto-generated by `python make_results_table.py` on {datetime.datetime.now():%Y-%m-%d %H:%M}. "
          "Don't edit by hand. Design notes and rationale for each variant are in [model_log.md](model_log.md).*", "",
          "All numbers are on `public_evaluation_data.json` (157 questions).", "",
          f"**Corpus version `{version}`**: `{CORPUS}`, {n_docs:,} documents, last scraped {modified:%Y-%m-%d %H:%M}. "
          "Only results computed on this exact corpus are shown. If you re-scrape, the tables empty out "
          "until the experiments are re-run, so numbers from different scrapes are never mixed.", ""]

    md += ["## End-to-end QA (report table `tab:results`)", "",
           "| System | Recall | F1 | ROUGE-L | Judge | Leaderboard Total |", "|---|---|---|---|---|---|"]
    for stem, name, r in qa:
        md.append("| " + " | ".join([name] + qa_row(stem, r["scores"], leaderboard)) + " |")
    if not qa:
        md.append("| *[no runs yet]* | | | | | |")
    md += ["", "Recall / F1 / ROUGE-L are ×100 (SQuAD-normalized, max over reference answers). "
           "Judge = mean 1–5 score from `judge.py`. Leaderboard Total comes from `leaderboard_scores.json` "
           "(\"--\" = not submitted). LaTeX version: `latex/results_table.tex`.", ""]
    if qa:
        md += ["### QA variants tested", "", "| System | Setup | n | EM | Answer in retrieved context | Command |",
               "|---|---|---|---|---|---|"]
        for stem, name, r in qa:
            s = r["scores"]
            ctx = pct(s, "answer_in_context") or "–"
            md.append(f"| {name} | {setup(r['config'])} | {s['n']} | {pct(s, 'em')} | {ctx} | `{r['command']}` |")
        md.append("")

    md += ["## Retrieval only (no LLM)", "",
           "**hit@k** = % of questions where a reference answer string appears in the top-k chunks. "
           "*All* = all 157 questions; *answerable* = only questions whose answer is somewhere in the corpus "
           "(a fairer comparison of retrievers, since no retriever can find a missing answer).", "",
           "| Chunking | Chunks | Retriever | " + " | ".join(f"hit@{k} all / ans." for k in KS) + " |",
           "|---|---|---|" + "---|" * len(KS)]
    best = max(retr, key=lambda r: r["hit_answerable"]["5"], default=None)
    for r in retr:
        cells = [f"{100 * r['hit_all'][k]:.1f} / {100 * r['hit_answerable'][k]:.1f}" for k in KS]
        if r is best:
            cells[2] = f"**{cells[2]}**"
        md.append(f"| {r['chunking']}-{r['chunk_size']} | {r['n_chunks']:,} | {retrieval_label(r)} | " + " | ".join(cells) + " |")
    if not retr:
        md.append("| *[no runs yet]* | | |" + " |" * len(KS))
    else:
        md += ["", f"Answerable subset: n={best['n_answerable']}. Bold = best hit@5 so far "
               f"({best['chunking']}-{best['chunk_size']}, {retrieval_label(best)}).",
               "", "Command for any row: `python eval_retrieval.py --chunking C --chunk-size N --retriever R "
               "[--fusion F --alpha A] [--rerank] [--embedder M]`"]
    if stale_qa or stale_retr:
        md += ["", "## Older results (hidden: computed on a previous corpus)", "",
               f"{len(stale_retr)} retrieval runs and {len(stale_qa)} QA runs were computed on an earlier scrape, so they "
               "are left out of the tables above. Re-run them to bring them back "
               "(the notebook's skip check only counts runs on the current corpus).", ""]
        md += [f"- QA: {name} (`{stem}`)" for stem, name, _ in stale_qa]
        md += [f"- retrieval: {r['chunking']}-{r['chunk_size']} {retrieval_label(r)}" for r in stale_retr]
    return "\n".join(md) + "\n"


def build_latex(qa, leaderboard):
    n = sorted({r["scores"]["n"] for _, _, r in qa}) or [157]
    tex = [r"\begin{table}[t]", r"  \centering", r"  \begin{tabular}{lrrrrr}", r"    \toprule",
           rf"    & \multicolumn{{4}}{{c}}{{Public eval ({'/'.join(map(str, n))} q)}} & Leaderboard \\",
           r"    \cmidrule(lr){2-5}", r"    System & Recall & F1 & ROUGE-L & Judge & Total \\", r"    \midrule"]
    for stem, name, r in qa:
        tex_name = name.replace("&", r"\&").replace("_", r"\_")
        tex.append("    " + " & ".join([tex_name] + qa_row(stem, r["scores"], leaderboard)) + r" \\")
    tex += [r"    \bottomrule", r"  \end{tabular}",
            r"  \caption{Results on the public evaluation set, with leaderboard scores for the",
            r"           systems we submitted.}", r"  \label{tab:results}", r"\end{table}"]
    return "\n".join(tex) + "\n"


def main():
    leaderboard = {}
    if os.path.exists("leaderboard_scores.json"):
        with open("leaderboard_scores.json") as f:
            leaderboard = json.load(f)
    version = corpus_version()
    (qa, stale_qa), (retr, stale_retr) = load_qa_runs(version), load_retrieval_runs(version)
    with open("RESULTS.md", "w") as f:
        f.write(build_markdown(qa, retr, leaderboard, version, stale_qa, stale_retr))
    with open("latex/results_table.tex", "w") as f:
        f.write(build_latex(qa, leaderboard))
    print(f"RESULTS.md: corpus {version}, {len(qa)} QA runs, {len(retr)} retrieval runs ({len(stale_qa) + len(stale_retr)} older hidden)")


if __name__ == "__main__":
    main()
